public class Loops {
    public static void main(String[] args) {

        // For loop
        for (int i = 0; i <= 10; i++) {
            System.out.print(i + " ");
        }

        
        //While loop
        int j = 0;
        while (j <= 10) {
            System.out.print(j + " ");
            j++;
        }


        //do-while loop
        int k = 0;
        do {
            System.out.print(k + " ");
            k++;
        } while (k <= 10);

    }
}
