public class ArrayTraversal {
    public static void main(String[] args) {
        int[] arr = {10, 20, 30, 40, 50};
        
        // Loop through the entire array
        for (int i = 0; i < arr.length; i++) {
            System.out.println("Value at index " + i + " is: " + arr[i]);
        }
    }
}